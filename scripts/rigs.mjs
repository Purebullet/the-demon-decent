const near = (a, b, r) => (p) => {
  // Within r of the segment a-b.
  const ab = [b[0] - a[0], b[1] - a[1], b[2] - a[2]];
  const ap = [p.x - a[0], p.y - a[1], p.z - a[2]];
  const l = ab[0] ** 2 + ab[1] ** 2 + ab[2] ** 2;
  const t = Math.max(0, Math.min(1, (ap[0] * ab[0] + ap[1] * ab[1] + ap[2] * ab[2]) / l));
  return Math.hypot(ap[0] - ab[0] * t, ap[1] - ab[1] * t, ap[2] - ab[2] * t) < r;
};

