// Coordinates are in the rig frame: the model faces +Z, its left is +X, it
// stands on y = 0 and is 1 tall. Joints named Left* are mirrored onto the
// right unless the right is given too. `snap` centres those joints (both
// sides) in the limb's cross-section within that radius. `r` is each bone's
// thickness: a vertex goes to the bones it is nearest to relative to their
// thickness. `limit` keeps a bone to a region ({ x: [min, max], ... }), so a
// hand never takes the thigh it hangs next to. `rigid` binds whole parts
// (a staff) to one bone.
//
// `attacks` names the motion (scripts/motions.mjs) each of the creature's
// attacks plays; a model shared by an enemy and a boss carries both sets.

