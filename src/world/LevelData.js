// The ten floors of the descent. Nothing here is procedural at run time:
// edit a map or a number and that floor changes, every run, for everyone.
// The non-boss maps were laid out by scripts/make-maps.mjs (one main path
// from left to right, rooms joined by short passages, a few dead ends and
// one loop) and can be edited by hand like any other.
//
// Each tile is 2 m. Rows may differ in length; the parser pads them with rock
// and seals the outer border, so you can sketch freely.
//
//   #  rock wall            .  floor             P  player spawn
//   X  exit portal (opens when the floor is cleared)
//   o  rock pillar          t  brazier (solid, lit)
//   g  gaunt stalker        c  shadow fiend      b  flame-horned brute
//   d  cinder hound         m  pyre witch (keeps her distance, throws fire)
//   G  burrowed stalker (ambush, erupts when you pass)
//   B  boss                 h  health potion     w  weapon cache
//   ~  lava (burns)         ^  spike trap        v  fire vent
//
// Tuning, per floor:
//   hp / dmg     enemy health and damage multipliers
//   speed        enemy movement speed multiplier
//   windup       attack telegraph duration multiplier (lower = tighter)
//   cooldown     time between an enemy's attacks multiplier
//   attackers    how many enemies may commit to an attack at once
//   swarm        pack behaviours: encircle, synchronized lunges, alerts
//   aggro        detection radius in metres
//   fog          fog density; light = torch radius in metres
//   loot         drop-chance multiplier
//   look         how the cavern looks: palette, light and props (world/themes.js)

export const TILE = 2;

// Below the fifth floor lies the Deep: its demons have a fifth more health,
// are 5% quicker on their feet and 5% quicker with their blows and powers
// (shorter wind-ups and cooldowns), on top of each floor's own tuning. The
// Deep is harder above all for how its demons fight (packs that close in
// together, ambushers, traps, champions at the exits).
//
// And each floor past the sixth (bosses aside) is worse again than the one
// above: its demons have 15% more health, strike 10% faster (wind-ups and
// cooldowns) and hit 5% harder, compounding (DEEPER). Some floors are
// tougher still (`hpBoost`: their demons' health on top of all that).
export const DEEP_FROM = 6;
export const DEEPER = { from: 6, hp: 1.15, pace: 1.1, dmg: 1.05 };
export function floorDef(floor) {
  const def = FLOORS[floor - 1];
  if (floor < DEEP_FROM) return def;
  const k = def.boss ? 0 : Math.max(0, floor - DEEPER.from);
  const pace = 1.05 * DEEPER.pace ** k;
  return { ...def, hp: def.hp * 1.2 * DEEPER.hp ** k * (def.hpBoost ?? 1), dmg: def.dmg * DEEPER.dmg ** k, speed: def.speed * 1.05, windup: def.windup / pace, cooldown: def.cooldown / pace };
}

